fn paint_data(
    p: &egui::Painter,
    rect: egui::Rect,
    extent: egui::Vec2,
    data: &[Primitive],
    color: egui::Color32,
) {
    let scale = (rect.width() / extent.x).min(rect.height() / extent.y);
    let origin = rect.center() - extent * scale * 0.5;
    let point = |v: [f32; 2]| origin + egui::vec2(v[0], v[1]) * scale;
    for item in data {
        let (fill, stroke) = match item {
            Primitive::Path(_, _, s, f) | Primitive::Circle(_, _, s, f) => (*f, *s),
        };
        let fill = match fill {
            1 => color,
            2 => theme::BACKGROUND,
            _ => egui::Color32::TRANSPARENT,
        };
        let line = egui::Stroke::new(stroke * scale, color);
        match item {
            Primitive::Circle(c, r, _, _) => {
                p.circle(point(*c), r * scale, fill, line);
            }
            Primitive::Path(values, closed, _, _) => {
                let points: Vec<_> = values.iter().map(|v| point(*v)).collect();
                if fill != egui::Color32::TRANSPARENT {
                    p.add(egui::Shape::convex_polygon(
                        points.clone(),
                        fill,
                        egui::Stroke::NONE,
                    ));
                }
                if stroke > 0. {
                    if *closed {
                        p.add(egui::Shape::closed_line(points, line));
                    } else {
                        if let (Some(a), Some(b)) = (points.first(), points.last()) {
                            p.circle_filled(*a, line.width * 0.5, color);
                            p.circle_filled(*b, line.width * 0.5, color);
                        }
                        p.add(egui::Shape::line(points, line));
                    }
                }
            }
        }
    }
}
pub fn paint(p: &egui::Painter, rect: egui::Rect, icon: Icon, color: egui::Color32) {
    paint_data(
        p,
        rect,
        egui::vec2(24., 24.),
        artwork(icon, rect.width().min(rect.height())),
        color,
    );
}

